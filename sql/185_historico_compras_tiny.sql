-- =====================================================================
-- 185 · Histórico das ordens de compra do Tiny (só consulta)
--  · Com o Tiny sendo desligado, as ordens de compra feitas lá ficam guardadas no sistema para consulta:
--    de quem compramos, o quê, quantidade, preço, IPI, frete e a situação que tinham no Tiny.
--  · Uma linha por item de cada ordem. As canceladas não entram.
--  · É só consulta: ninguém cria nem altera por tela; os dados vêm das planilhas exportadas do Tiny.
--    Não mexe em pedidos de compra, contas a pagar nem estoque, e não gera aviso para ninguém.
--  · Quem vê: quem tem acesso a Pedidos de compra.
--  · Para desfazer: basta esconder a tela no menu (a tabela não afeta nada no sistema).
-- =====================================================================

create table if not exists public.historico_compras_tiny (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references public.empresas(id),
  oc_numero integer not null,
  linha integer not null,
  numero_fornecedor text,
  data_pedido date,
  data_prevista date,
  fornecedor_nome text not null,
  fornecedor_id bigint references public.fornecedores(id),
  situacao text not null check (situacao in ('atendido', 'em_aberto', 'em_andamento')),
  item text not null,
  sku text,
  quantidade numeric(14,4),
  valor_unitario numeric(14,4),
  valor_produto numeric(14,2),
  desconto numeric(14,2) not null default 0,
  frete numeric(14,2) not null default 0,
  ipi numeric(14,2) not null default 0,
  icms numeric(14,2) not null default 0,
  total numeric(14,2),
  observacoes text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (empresa_id, oc_numero, linha)
);
create index if not exists historico_compras_tiny_forn on public.historico_compras_tiny (fornecedor_id);
create index if not exists historico_compras_tiny_data on public.historico_compras_tiny (data_pedido);

alter table public.historico_compras_tiny enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'historico_compras_tiny' and policyname = 'ver historico tiny') then
    create policy "ver historico tiny" on public.historico_compras_tiny for select to authenticated
      using ((select public.pode('compras')));
  end if;
end $$;
revoke all on table public.historico_compras_tiny from anon;
revoke insert, update, delete on table public.historico_compras_tiny from authenticated;   -- só consulta

select public.ligar_auditoria('historico_compras_tiny');
select public.ligar_tempo_real('historico_compras_tiny');
