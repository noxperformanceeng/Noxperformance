alter table public.solicitacoes_compra add column if not exists vista_comprador_por uuid references public.usuarios(id);
alter table public.solicitacoes_compra_itens add column if not exists liberado_em timestamptz;
alter table public.solicitacoes_compra_itens add column if not exists liberado_por uuid references public.usuarios(id);
alter table public.solicitacoes_compra_itens add column if not exists retirado_em timestamptz;
alter table public.solicitacoes_compra_itens add column if not exists retirado_por uuid references public.usuarios(id);   -- quem registrou
alter table public.solicitacoes_compra_itens add column if not exists retirado_quem uuid references public.usuarios(id);  -- quem retirou
alter table public.solicitacoes_compra_itens add column if not exists retirado_obs text;

-- ---------- Chegadas no almoxarifado (etapa 1 e 2) ----------
create table if not exists public.almox_chegadas (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos_compra(id) on delete cascade,
  chegou_em timestamptz not null default now(),
  registrado_por uuid default auth.uid() references public.usuarios(id),
  nf_numero text,
  volumes integer check (volumes is null or volumes > 0),
  observacao text,
  conferido_em timestamptz,
  conferido_por uuid references public.usuarios(id),
  recebimento_id bigint references public.pedidos_compra_recebimentos(id) on delete set null
);
create index if not exists almox_chegadas_pedido on public.almox_chegadas (pedido_id);
create index if not exists almox_chegadas_abertas on public.almox_chegadas (pedido_id) where conferido_em is null;
alter table public.almox_chegadas enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'almox_chegadas' and policyname = 'ver chegadas') then
    create policy "ver chegadas" on public.almox_chegadas for select to authenticated
      using ((select public.pode('almoxarifado')) or (select public.pode('compras')));
  end if;
end $$;
revoke all on table public.almox_chegadas from anon;
revoke insert, update, delete on table public.almox_chegadas from authenticated;   -- só pelas funções abaixo

-- Etapa 1: chegou
create or replace function public.almox_registrar_chegada(p_pedido bigint, p_nf text, p_volumes integer, p_obs text)
returns bigint language plpgsql security definer set search_path = public as $$
declare p public.pedidos_compra; v_id bigint;
begin
  if not (public.pode('almoxarifado', 'criar') or public.pode('estoque', 'alterar') or public.pode('compras', 'alterar')) then
    raise exception 'Sem permissão para registrar chegada';
  end if;
  select * into p from public.pedidos_compra where id = p_pedido;
  if p.id is null then raise exception 'Pedido não encontrado'; end if;
  if p.situacao not in ('aprovado', 'enviado', 'recebido_parcial') then raise exception 'O pedido % não está aguardando entrega', p.numero; end if;
  if exists (select 1 from public.almox_chegadas where pedido_id = p_pedido and conferido_em is null) then
    raise exception 'Já há uma chegada do % aguardando conferência', p.numero;
  end if;
  insert into public.almox_chegadas (pedido_id, nf_numero, volumes, observacao)
  values (p_pedido, nullif(upper(trim(coalesce(p_nf, ''))), ''), p_volumes, nullif(upper(trim(coalesce(p_obs, ''))), ''))
  returning id into v_id;
  perform public.pc_evento(p_pedido, 'chegou', 'Mercadoria chegou no almoxarifado'
    || coalesce(' · NF ' || nullif(upper(trim(coalesce(p_nf, ''))), ''), '') || coalesce(' · ' || p_volumes || ' volume(s)', '') || ' · aguardando conferência');
  return v_id;
end $$;
revoke execute on function public.almox_registrar_chegada(bigint, text, integer, text) from public, anon;
grant execute on function public.almox_registrar_chegada(bigint, text, integer, text) to authenticated;

-- Desfazer a chegada (registrada por engano), enquanto não conferida
create or replace function public.almox_desfazer_chegada(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare c public.almox_chegadas;
begin
  if not (public.pode('almoxarifado', 'criar') or public.pode('estoque', 'alterar') or public.pode('compras', 'alterar')) then
    raise exception 'Sem permissão';
  end if;
  select * into c from public.almox_chegadas where id = p_id;
  if c.id is null then raise exception 'Chegada não encontrada'; end if;
  if c.conferido_em is not null then raise exception 'Já foi conferida: não dá para desfazer'; end if;
  delete from public.almox_chegadas where id = p_id;
  perform public.pc_evento(c.pedido_id, 'chegada_desfeita', 'Registro de chegada desfeito');
end $$;
revoke execute on function public.almox_desfazer_chegada(bigint) from public, anon;
grant execute on function public.almox_desfazer_chegada(bigint) to authenticated;

-- Etapa 2: a conferência é a entrada da NF de hoje. Ao gravar a entrada, a chegada aberta vira "conferida"
-- (se ninguém registrou a chegada antes, ela nasce já conferida).
create or replace function public.almox_conferido()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  select id into v_id from public.almox_chegadas where pedido_id = new.pedido_id and conferido_em is null order by id limit 1;
  if v_id is null then
    insert into public.almox_chegadas (pedido_id, chegou_em, registrado_por, nf_numero, conferido_em, conferido_por, recebimento_id)
    values (new.pedido_id, now(), auth.uid(), nullif(new.nf_numero, 'SEM NF'), now(), auth.uid(), new.id);
  else
    update public.almox_chegadas set conferido_em = now(), conferido_por = auth.uid(), recebimento_id = new.id,
      nf_numero = coalesce(nf_numero, nullif(new.nf_numero, 'SEM NF')) where id = v_id;
  end if;
  return new;
end $$;
revoke execute on function public.almox_conferido() from public, anon, authenticated;
do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'almox_conferido' and tgrelid = 'public.pedidos_compra_recebimentos'::regclass) then
    create trigger almox_conferido after insert on public.pedidos_compra_recebimentos
      for each row execute function public.almox_conferido();
  end if;
end $$;

-- Etapa 3: liberar para retirada (itens de solicitação já conferidos) + recado para quem pediu
create or replace function public.almox_liberar_retirada(p_itens bigint[])
returns integer language plpgsql security definer set search_path = public as $$
declare n int; s record; v_ids bigint[];
begin
  if not (public.pode('almoxarifado', 'criar') or public.pode('estoque', 'alterar')) then raise exception 'Sem permissão'; end if;
  if exists (select 1 from public.solicitacoes_compra_itens i join public.pedidos_compra p on p.id = i.pedido_id
              where i.id = any(p_itens) and p.situacao not in ('recebido', 'recebido_parcial')) then
    raise exception 'Só libera item de pedido já conferido (com entrada dada)';
  end if;
  with u as (update public.solicitacoes_compra_itens set liberado_em = now(), liberado_por = auth.uid()
               where id = any(p_itens) and pedido_id is not null and liberado_em is null returning id)
  select coalesce(array_agg(id), '{}') into v_ids from u;
  n := cardinality(v_ids);
  for s in select sc.id, sc.numero, sc.solicitante_id,
                  string_agg(trim(to_char(i.quantidade, 'FM999999990.###'), '.') || '× ' || coalesce(pr.descricao, sv.nome, i.descricao), '; ' order by i.id) itens
             from public.solicitacoes_compra_itens i join public.solicitacoes_compra sc on sc.id = i.solicitacao_id
             left join public.produtos pr on pr.id = i.produto_id left join public.servicos sv on sv.id = i.servico_id
            where i.id = any(v_ids)
            group by sc.id, sc.numero, sc.solicitante_id loop
    if s.solicitante_id is not null and s.solicitante_id is distinct from auth.uid() and auth.uid() is not null then
      insert into public.recados (de_id, para_id, texto, link, prazo)
      values (auth.uid(), s.solicitante_id,
              'Chegou o material da sua solicitação ' || s.numero || ': ' || s.itens || '. Está LIBERADO para retirada no almoxarifado.',
              'pages/compras/solicitacoes.html?abrir=' || s.id, current_date + 2);
    end if;
  end loop;
  return n;
end $$;
revoke execute on function public.almox_liberar_retirada(bigint[]) from public, anon;
grant execute on function public.almox_liberar_retirada(bigint[]) to authenticated;

-- Etapa 4: retirada. Baixa do estoque o que entrou no estoque (produto que controla estoque e não é uso e consumo)
create or replace function public.almox_registrar_retirada(p_itens bigint[], p_quem uuid, p_obs text)
returns integer language plpgsql security definer set search_path = public as $$
declare n int; v_nome text;
begin
  if not (public.pode('almoxarifado', 'criar') or public.pode('estoque', 'alterar')) then raise exception 'Sem permissão'; end if;
  if p_quem is null then raise exception 'Informe quem retirou'; end if;
  select nome into v_nome from public.usuarios where id = p_quem;
  if exists (select 1 from public.solicitacoes_compra_itens where id = any(p_itens) and (liberado_em is null or retirado_em is not null)) then
    raise exception 'Só registra retirada de item liberado e ainda não retirado';
  end if;
  insert into public.estoque_movimentos (produto_id, tipo, quantidade, unidade, custo_unitario, pedido_compra_id, observacao, data)
  select i.produto_id, 'consumo', -least(i.quantidade, pi.quantidade_recebida), pr.unidade, public.estoque_custo_medio(i.produto_id), i.pedido_id,
         'RETIRADA ' || sc.numero || ' · ' || upper(coalesce(v_nome, '')) || coalesce(' · ' || nullif(upper(trim(coalesce(p_obs, ''))), ''), ''), current_date
    from public.solicitacoes_compra_itens i
    join public.solicitacoes_compra sc on sc.id = i.solicitacao_id
    join public.produtos pr on pr.id = i.produto_id
    join lateral (select x.quantidade_recebida, x.uso_consumo from public.pedidos_compra_itens x
                   where x.pedido_id = i.pedido_id and x.produto_id = i.produto_id order by x.id limit 1) pi on true
   where i.id = any(p_itens) and pr.controla_estoque and not pi.uso_consumo and pi.quantidade_recebida > 0;
  update public.solicitacoes_compra_itens set retirado_em = now(), retirado_por = auth.uid(), retirado_quem = p_quem,
         retirado_obs = nullif(upper(trim(coalesce(p_obs, ''))), '')
   where id = any(p_itens);
  get diagnostics n = row_count;
  update public.recados r set feito_em = now(), resposta = coalesce(r.resposta, 'Retirado')
   where r.feito_em is null and r.link in (select 'pages/compras/solicitacoes.html?abrir=' || i.solicitacao_id from public.solicitacoes_compra_itens i where i.id = any(p_itens))
     and not exists (select 1 from public.solicitacoes_compra_itens j where 'pages/compras/solicitacoes.html?abrir=' || j.solicitacao_id = r.link
                       and j.liberado_em is not null and j.retirado_em is null);
  return n;
end $$;
revoke execute on function public.almox_registrar_retirada(bigint[], uuid, text) from public, anon;
grant execute on function public.almox_registrar_retirada(bigint[], uuid, text) to authenticated;

-- ---------- Solicitação: visto pelo comprador ----------
create or replace function public.sc_marcar_vista(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not (public.pode('cotacoes_compra', 'criar') or public.pode('compras', 'criar')) then return; end if;
  update public.solicitacoes_compra set vista_comprador_em = now(), vista_comprador_por = auth.uid()
   where id = p_id and vista_comprador_em is null and situacao = 'aprovado' and solicitante_id is distinct from auth.uid();
end $$;
revoke execute on function public.sc_marcar_vista(bigint) from public, anon;
grant execute on function public.sc_marcar_vista(bigint) to authenticated;

-- ---------- Solicitação: andamento dos pedidos sem preço e sem fornecedor para quem não é de compras ----------
create or replace function public.sc_pedidos()
returns table (id bigint, numero text, situacao text, fornecedor text)
language sql stable security definer set search_path = public as $$
  select distinct p.id, p.numero, p.situacao, case when (select public.pode('compras')) then f.nome end
    from public.solicitacoes_compra_itens i join public.solicitacoes_compra s on s.id = i.solicitacao_id
    join public.pedidos_compra p on p.id = i.pedido_id left join public.fornecedores f on f.id = p.fornecedor_id
   where (select public.pode('solicitacoes_compra')) and (s.solicitante_id = auth.uid() or (select public.sc_ve_todas()))
$$;
revoke execute on function public.sc_pedidos() from public, anon;
grant execute on function public.sc_pedidos() to authenticated;

create or replace function public.sc_pedidos_andamento()
returns table (pedido_id bigint, chegou_em timestamptz, conferido_em timestamptz)
language sql stable security definer set search_path = public as $$
  select c.pedido_id, max(c.chegou_em), max(c.conferido_em)
    from public.almox_chegadas c
   where (select public.pode('solicitacoes_compra'))
     and exists (select 1 from public.solicitacoes_compra_itens i join public.solicitacoes_compra s on s.id = i.solicitacao_id
                  where i.pedido_id = c.pedido_id and (s.solicitante_id = auth.uid() or (select public.sc_ve_todas())))
   group by c.pedido_id
$$;
revoke execute on function public.sc_pedidos_andamento() from public, anon;
grant execute on function public.sc_pedidos_andamento() to authenticated;

-- ---------- Recebimento: itens de solicitação ligados aos pedidos (quem pediu, o quê, situação da retirada) ----------
create or replace function public.almox_itens_solicitacao()
returns table (item_id bigint, solicitacao_id bigint, solicitacao text, solicitante_id uuid, solicitante text, pedido_id bigint,
               descricao text, quantidade numeric, unidade text, liberado_em timestamptz, retirado_em timestamptz, retirado_quem text)
language sql stable security definer set search_path = public as $$
  select i.id, s.id, s.numero, s.solicitante_id, u.nome, i.pedido_id,
         coalesce(pr.codigo || ' ' || pr.descricao, sv.nome, i.descricao), i.quantidade, coalesce(i.unidade, pr.unidade, sv.unidade),
         i.liberado_em, i.retirado_em, uq.nome
    from public.solicitacoes_compra_itens i join public.solicitacoes_compra s on s.id = i.solicitacao_id
    join public.pedidos_compra p on p.id = i.pedido_id
    left join public.usuarios u on u.id = s.solicitante_id left join public.usuarios uq on uq.id = i.retirado_quem
    left join public.produtos pr on pr.id = i.produto_id left join public.servicos sv on sv.id = i.servico_id
   where ((select public.pode('almoxarifado')) or (select public.pode('compras')))
     and p.situacao <> 'cancelado' and (i.retirado_em is null or i.retirado_em > now() - interval '30 days')
$$;
revoke execute on function public.almox_itens_solicitacao() from public, anon;
grant execute on function public.almox_itens_solicitacao() to authenticated;

