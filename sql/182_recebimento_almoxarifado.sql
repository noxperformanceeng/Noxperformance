-- =====================================================================
-- 182 · Recebimento no almoxarifado + acompanhamento da solicitação de compra
--  · Nova tela "Recebimento" (Estoque → Recebimento) para o almoxarifado, em etapas:
--      1) CHEGOU      — registra que a mercadoria/caixa chegou (NF opcional, volumes, observação);
--      2) CONFERIDO   — confere item a item e dá entrada (a mesma "Entrada da NF" de hoje, que atualiza o estoque);
--      3) LIBERADO    — o que foi pedido numa solicitação fica separado e liberado para retirada (avisa o solicitante);
--      4) RETIRADO    — registra quem retirou e quando (baixa do estoque o que tinha entrado no estoque).
--  · Solicitação de compra: quem pediu acompanha o andamento — visto pelo comprador, em cotação, comprado,
--    chegou, conferido, liberado para retirada, retirado — SEM ver preço nem fornecedor.
--  · O comprador, ao abrir a solicitação, marca "visto pelo comprador" sozinho.
--  · Para desfazer: as colunas e a tabela novas podem ficar (não mexem no que existe); a tela some tirando o item do menu.
-- =====================================================================

-- ---------- Colunas novas ----------
