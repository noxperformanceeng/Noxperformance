-- =====================================================================
-- 177 · Anexos na ordem de compra
--  · Nova área "Anexos" no pedido de compra: fatura/orçamento do fornecedor, comprovante de
--    pagamento, nota fiscal, print da compra (Mercado Livre etc.) ou outro arquivo.
--  · Os arquivos ficam no bucket "compras", na pasta pedidos/<id do pedido>/.
--  · Quem vê o pedido (compras) ou o contas a pagar (financeiro) vê e abre os anexos.
--  · Anexa quem pode criar pedidos de compra, em qualquer etapa (menos cancelado).
--  · Exclui quem anexou ou o administrador.
--  · Para desfazer: os anexos podem ser excluídos na própria tela; a tabela nova não muda nada do que já existe.
-- =====================================================================

create table if not exists public.pedidos_compra_anexos (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos_compra(id) on delete cascade,
  tipo text not null default 'outro' check (tipo in ('fatura','comprovante','nota_fiscal','print','outro')),
  nome text not null,
  caminho text not null,          -- arquivo no bucket "compras" (pedidos/<pedido_id>/...)
  mime text,
  tamanho bigint,
  criado_em timestamptz not null default now(),
  criado_por uuid default auth.uid()
);
create index if not exists pedidos_compra_anexos_pedido on public.pedidos_compra_anexos (pedido_id);
alter table public.pedidos_compra_anexos enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'pedidos_compra_anexos' and policyname = 'ver anexos pedido') then
    create policy "ver anexos pedido" on public.pedidos_compra_anexos for select to authenticated
      using ((select public.pode('compras')) or (select public.pode('pagar')));
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'pedidos_compra_anexos' and policyname = 'incluir anexos pedido') then
    create policy "incluir anexos pedido" on public.pedidos_compra_anexos for insert to authenticated
      with check ((select public.pode('compras', 'criar')) and criado_por = (select auth.uid())
                  and exists (select 1 from public.pedidos_compra p where p.id = pedido_id and p.situacao <> 'cancelado'));
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'pedidos_compra_anexos' and policyname = 'excluir anexos pedido') then
    create policy "excluir anexos pedido" on public.pedidos_compra_anexos for delete to authenticated
      using ((select public.eh_admin()) or (criado_por = (select auth.uid()) and (select public.pode('compras', 'criar'))));
  end if;
end $$;
revoke all on table public.pedidos_compra_anexos from anon;

-- O financeiro (contas a pagar) também abre os anexos dos pedidos, mesmo sem acesso a compras
alter policy "compras ler" on storage.objects
  using (bucket_id = 'compras' and ((select public.pode('compras')) or ((select public.pode('pagar')) and name like 'pedidos/%')));

select public.ligar_auditoria('pedidos_compra_anexos');
select public.ligar_tempo_real('pedidos_compra_anexos');
