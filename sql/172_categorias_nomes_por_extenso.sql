--  · A transferência entre contas passa a achar suas categorias pelo código, não pelo nome.
--  · As categorias antigas do Tiny (grupo 99, inativas) ficam como estão.
--  · Para desfazer: o nome anterior de cada categoria fica na auditoria.
-- =====================================================================

